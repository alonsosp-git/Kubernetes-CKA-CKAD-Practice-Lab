# --------------------------------------------------------------------------
# versions
# --------------------------------------------------------------------------
RELEASES = ["1.28.11", "1.29.7", "1.30.2", "1.31.1", "1.32.0"]



def _digest(text: str) -> str:
    """A short, stable, non-cryptographic id. Never used for security.

    `usedforsecurity=False` is not a performance hint -- it is the declaration
    that this digest authenticates nothing, which is also what lets the build
    run on a FIPS-enforcing host where SHA-1 is otherwise unavailable.
    """
    return hashlib.sha1(text.encode(), usedforsecurity=False).hexdigest()

def parse_version(text: str) -> Tuple[int, int, int]:
    parts = re.findall(r"\d+", str(text).lstrip("v"))
    parts += ["0"] * (3 - len(parts))
    return tuple(int(p) for p in parts[:3])            # type: ignore[return-value]


def minor(text: str) -> Tuple[int, int]:
    major, minor_, _ = parse_version(text)
    return major, minor_


def next_release(current: str) -> Optional[str]:
    current_minor = minor(current)
    for release in RELEASES:
        if minor(release) > current_minor:
            return release
    return None


def node_version(node: dict) -> str:
    return str(deep_get(node, "status.nodeInfo.kubeletVersion", "v1.30.2")).lstrip("v")


def set_node_version(node: dict, version: str) -> None:
    node.setdefault("status", {}).setdefault("nodeInfo", {})["kubeletVersion"] = \
        f"v{version.lstrip('v')}"


def skew_ok(control_plane: str, kubelet: str) -> bool:
    """kubelet may be up to 3 minor versions behind the API server, never ahead."""
    cp_major, cp_minor = minor(control_plane)
    k_major, k_minor = minor(kubelet)
    if (k_major, k_minor) > (cp_major, cp_minor):
        return False
    return (cp_major, cp_minor) <= (k_major, k_minor + 3)


