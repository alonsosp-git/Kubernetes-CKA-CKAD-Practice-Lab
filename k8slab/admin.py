PUBLIC_IMAGES = (
    "nginx", "busybox", "postgres", "redis", "alpine", "python", "node", "mysql",
    "mongo", "httpd", "traefik", "prom/node-exporter", "fluent/fluent-bit",
    "registry.k8s.io/ingress-nginx/controller", "hashicorp/http-echo",
    "grafana/grafana", "prom/prometheus", "quay.io/prometheus/alertmanager",
    # images the labs themselves ship -- they must pull, or the lesson is wrong
    "lab.example.com/backup-operator",
)


def image_known(cluster: Cluster, image: str) -> Tuple[bool, bool]:
    """(pullable by a node, private) for an image reference.

    Built locally but never pushed == not pullable: a kubelet fetches over the
    network and cannot reach your workstation.
    """
    reference = str(image)
    for candidate in (reference, reference.rsplit(":", 1)[0]):
        meta = cluster.registry.get(candidate)
        if meta is not None:
            return bool(meta.get("pushed")), bool(meta.get("private"))
    repository = reference.rsplit(":", 1)[0]
    for known in PUBLIC_IMAGES:
        if repository == known or repository.endswith("/" + known):
            return True, False
    return False, False


def docker(cluster: Cluster, args: List[str], flags: Dict[str, Any]) -> Tuple[bool, str]:
    """A tiny local registry so image pulls can succeed, fail or need credentials."""
    if not args:
        return True, DOCKER_HELP
    action = args[0]

    if action == "build":
        tag = flags.get("-t") or flags.get("--tag")
        if not tag:
            return False, 'usage: docker build -t <name>:<tag> .'
        digest = "sha256:" + hashlib.sha256(f"{tag}{cluster.tick}".encode()).hexdigest()[:12]
        cluster.registry[tag] = {"private": False, "digest": digest, "built": True,
                                 "pushed": False}
        return True, (f"[+] Building 2.4s (7/7) FINISHED\n"
                      f" => exporting to image\n"
                      f" => => naming to docker.io/library/{tag}\n"
                      f" => => writing image {digest}\n\n"
                      f"Built {tag}. It exists on this machine only until you push it -- "
                      "a Kubernetes node cannot pull from your laptop.")

    if action == "tag":
        if len(args) < 3:
            return False, "usage: docker tag <source> <target>"
        source, target = args[1], args[2]
        if source not in cluster.registry:
            exists, _ = image_known(cluster, source)
            if not exists:
                return False, f"Error response from daemon: No such image: {source}"
        cluster.registry[target] = dict(cluster.registry.get(source, {"digest": "sha256:public"}))
        cluster.registry[target]["pushed"] = False
        return True, ""

    if action == "push":
        reference = args[1] if len(args) > 1 else ""
        if reference not in cluster.registry:
            return False, (f"An image does not exist locally with the tag: {reference}\n"
                           "build or tag it first")
        private = "private" in reference or bool(flags.get("--private"))
        cluster.registry[reference].update({"pushed": True, "private": private})
        return True, (f"The push refers to repository [{reference.rsplit(':', 1)[0]}]\n"
                      f"latest: digest: {cluster.registry[reference]['digest']} size: 1571\n"
                      + ("\nThis repository is PRIVATE: pods need an imagePullSecret "
                         "(kubectl create secret docker-registry ...)." if private else ""))

    if action == "images":
        rows = ["REPOSITORY                          TAG        DIGEST          "
                "PUSHED   PRIVATE"]
        for reference, meta in sorted(cluster.registry.items()):
            repository, _, tag = reference.partition(":")
            rows.append(f"{repository:<35} {tag or 'latest':<10} "
                        f"{meta.get('digest', '')[:14]:<15} "
                        f"{str(meta.get('pushed', False)):<8} "
                        f"{meta.get('private', False)}")
        if len(rows) == 1:
            rows.append("(nothing built yet -- try: docker build -t myapp:1.0 .)")
        return True, "\n".join(rows)

    if action == "rmi":
        reference = args[1] if len(args) > 1 else ""
        cluster.registry.pop(reference, None)
        return True, f"Untagged: {reference}"

    return False, (f"unknown docker command: {action}\n"
                   "This lab models a registry, not a real Docker daemon: build, tag, "
                   "push, images, rmi.")


