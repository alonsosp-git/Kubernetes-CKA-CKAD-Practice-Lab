def make_csr(cluster: Cluster, name: str, user: str, groups: List[str]) -> dict:
    return {
        "apiVersion": "certificates.k8s.io/v1",
        "kind": "CertificateSigningRequest",
        "metadata": {"name": name, "uid": cluster.next_uid(),
                     "creationTick": cluster.tick, "labels": {}, "annotations": {}},
        "spec": {"request": "<base64 PEM CSR>", "signerName":
                 "kubernetes.io/kube-apiserver-client",
                 "username": user, "groups": groups or ["system:authenticated"],
                 "usages": ["client auth"], "expirationSeconds": 86400},
        "status": {"phase": "Pending"},
    }


def certificate(cluster: Cluster, args: List[str]) -> Tuple[bool, str]:
    """kubectl certificate approve|deny <name>"""
    if len(args) < 2:
        return False, "usage: kubectl certificate approve|deny <csr-name>"
    action, name = args[0], args[1]
    csr = cluster.get("CertificateSigningRequest", "", name)
    if csr is None:
        return False, f'certificatesigningrequests "{name}" not found'
    if action == "approve":
        csr.setdefault("status", {}).update({
            "phase": "Approved,Issued",
            "conditions": [{"type": "Approved", "status": "True",
                            "reason": "KubectlApprove"}],
            "certificate": "<base64 PEM certificate>"})
        user = deep_get(csr, "spec.username")
        cluster.kubeconfig.setdefault("users", {})[user] = {
            "client-certificate": f"{user}.crt", "client-key": f"{user}.key",
            "groups": deep_get(csr, "spec.groups", []) or [], "expires_in_days": 1}
        cluster.record("Normal", "CSRApproved", f"CSR {name} approved and issued",
                       f"certificatesigningrequest/{name}", "default")
        return True, (f"certificatesigningrequest.certificates.k8s.io/{name} approved\n"
                      f"\nExtract the certificate with:\n"
                      f"  kubectl get csr {name} -o jsonpath='{{.status.certificate}}' "
                      "| base64 -d > " + f"{user}.crt")
    if action == "deny":
        csr.setdefault("status", {}).update({
            "phase": "Denied",
            "conditions": [{"type": "Denied", "status": "True"}]})
        return True, f"certificatesigningrequest.certificates.k8s.io/{name} denied"
    return False, f"unknown certificate action: {action}"


def kubeconfig_command(cluster: Cluster, args: List[str],
                       flags: Dict[str, Any]) -> Tuple[bool, str]:
    """The kubeconfig half of `kubectl config`."""
    action = args[0]
    config = cluster.kubeconfig

    if action == "set-credentials":
        user = args[1] if len(args) > 1 else ""
        if not user:
            return False, "usage: kubectl config set-credentials <user> [flags]"
        entry = config.setdefault("users", {}).setdefault(user, {})
        for flag, key in (("--client-certificate", "client-certificate"),
                          ("--client-key", "client-key"),
                          ("--token", "token")):
            if flags.get(flag):
                entry[key] = flags[flag]
        entry.setdefault("expires_in_days", 1)
        return True, f'User "{user}" set.'

    if action == "set-cluster":
        name = args[1] if len(args) > 1 else ""
        config.setdefault("clusters", {})[name] = {
            "server": flags.get("--server", "https://127.0.0.1:6443"),
            "certificate-authority": flags.get("--certificate-authority", "ca.crt")}
        return True, f'Cluster "{name}" set.'

    if action == "set-context":
        name = args[1] if len(args) > 1 else "--current"
        if name == "--current" or flags.get("--current"):
            name = config.get("current-context", "lab")
        entry = config.setdefault("contexts", {}).setdefault(
            name, {"cluster": "lab-cluster", "user": "admin", "namespace": "default"})
        for flag, key in (("--cluster", "cluster"), ("--user", "user"),
                          ("--namespace", "namespace")):
            if flags.get(flag):
                entry[key] = flags[flag]
        if flags.get("--namespace"):
            namespace = flags["--namespace"]
            if not cluster.get("Namespace", "", namespace):
                return False, f'namespace "{namespace}" not found'
            if name == config.get("current-context"):
                cluster.current_namespace = namespace
        return True, f'Context "{name}" modified.'

    if action == "use-context":
        name = args[1] if len(args) > 1 else ""
        if name not in config.get("contexts", {}):
            return False, (f'no context exists with the name: "{name}"\n'
                           "create one first: kubectl config set-context "
                           f"{name} --cluster=lab-cluster --user=<user>")
        config["current-context"] = name
        context = config["contexts"][name]
        cluster.current_user = context.get("user", "admin")
        cluster.current_namespace = context.get("namespace", "default")
        return True, f'Switched to context "{name}".'

    if action == "get-contexts":
        rows = ["CURRENT   NAME       CLUSTER       AUTHINFO   NAMESPACE"]
        for name, context in config.get("contexts", {}).items():
            mark = "*" if name == config.get("current-context") else " "
            rows.append(f"{mark:<9} {name:<10} {context.get('cluster', ''):<13} "
                        f"{context.get('user', ''):<10} {context.get('namespace', '')}")
        return True, "\n".join(rows)

    if action == "get-users":
        return True, "NAME\n" + "\n".join(config.get("users", {}))

    if action == "current-context":
        return True, config.get("current-context", "lab")

    if action == "view":
        from . import miniyaml
        return True, miniyaml.dump({
            "apiVersion": "v1", "kind": "Config",
            "current-context": config.get("current-context"),
            "clusters": [{"name": n, "cluster": c}
                         for n, c in config.get("clusters", {}).items()],
            "users": [{"name": n,
                       "user": {k: v for k, v in u.items()
                                if k not in ("groups", "expires_in_days")}}
                      for n, u in config.get("users", {}).items()],
            "contexts": [{"name": n, "context": c}
                         for n, c in config.get("contexts", {}).items()]})
    return False, f"unknown config action: {action}"


