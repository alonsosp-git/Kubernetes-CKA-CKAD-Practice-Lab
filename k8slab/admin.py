def kubeadm(cluster: Cluster, args: List[str], flags: Dict[str, Any]) -> Tuple[bool, str]:
    if not args:
        return True, KUBEADM_HELP
    action = args[0]

    if action == "version":
        return True, (f"kubeadm version: &version.Info{{Major:\"{minor(cluster.version)[0]}\", "
                      f"Minor:\"{minor(cluster.version)[1]}\", "
                      f"GitVersion:\"v{cluster.version}\"}}")

    if action == "token":
        sub = args[1] if len(args) > 1 else "list"
        # Cosmetic only: a fake kubeadm join token so the output looks real.
        # usedforsecurity=False says so explicitly -- this is not authenticating
        # anything, and no real token is ever generated by this program.
        token = (_digest(f"{cluster.tick}")[:6] + "." +
                 _digest(f"{cluster.tick}x")[:16])
        if sub == "create":
            if flags.get("--print-join-command"):
                return True, (f"kubeadm join 172.18.0.2:6443 --token {token} "
                              f"--discovery-token-ca-cert-hash sha256:"
                              f"{hashlib.sha256(cluster.name.encode()).hexdigest()}")
            return True, token
        return True, ("TOKEN                     TTL         USAGES\n"
                      f"{token}   23h         authentication,signing")

    if action == "join":
        name = flags.get("--node-name") or f"lab-worker-{len(cluster.list('Node'))}"
        if cluster.get("Node", "", name):
            return False, f'node "{name}" already exists in the cluster'
        if not any(a.startswith("--token") or a == "--token" for a in args + list(flags)):
            return False, ("a bootstrap token is required: run `kubeadm token create "
                           "--print-join-command` on the control plane first")
        node = add_node(cluster, name)
        set_node_version(node, cluster.version)
        cluster.record("Normal", "NodeJoined",
                       f"Node {name} joined the cluster via kubeadm",
                       f"node/{name}", "default")
        return True, ("[preflight] Running pre-flight checks\n"
                      "[kubelet-start] Starting the kubelet\n"
                      "[tls-bootstrap] Waiting for the kubelet to perform the TLS "
                      "bootstrap\n\n"
                      f"This node has joined the cluster: {name}\n"
                      "Run 'kubectl get nodes' on the control plane to see it.")

    if action == "upgrade":
        return _kubeadm_upgrade(cluster, args[1:], flags)

    if action == "certs":
        return _kubeadm_certs(cluster, args[1:], flags)

    if action == "init":
        return False, ("this cluster is already initialised. `kubeadm init` builds a "
                       "control plane from scratch on a real machine -- practise it "
                       "on kind/minikube. Here, start from `kubeadm upgrade plan`.")

    if action == "reset":
        return False, "refusing to reset the lab control plane (use `sim reset`)"

    return False, f"unknown kubeadm command: {action}"


def _kubeadm_upgrade(cluster: Cluster, args: List[str],
                     flags: Dict[str, Any]) -> Tuple[bool, str]:
    sub = args[0] if args else "plan"
    control_plane = cluster.version
    target = next_release(control_plane)

    if sub == "plan":
        lines = ["[upgrade/config] Reading configuration from the cluster...",
                 "",
                 "Components that must be upgraded manually after you have upgraded "
                 "the control plane with 'kubeadm upgrade apply':",
                 "COMPONENT   CURRENT             TARGET"]
        counts: Dict[str, int] = {}
        for node in cluster.list("Node"):
            counts[node_version(node)] = counts.get(node_version(node), 0) + 1
        for version, count in sorted(counts.items()):
            lines.append(f"kubelet     {count} x v{version:<12}   "
                         f"v{target or control_plane}")
        lines += ["", "Upgrade to the latest stable version:", "",
                  "COMPONENT                 CURRENT   TARGET",
                  f"kube-apiserver            v{control_plane}   v{target or control_plane}",
                  f"kube-controller-manager   v{control_plane}   v{target or control_plane}",
                  f"kube-scheduler            v{control_plane}   v{target or control_plane}",
                  f"kubeadm                   v{control_plane}   v{target or control_plane}",
                  ""]
        if target:
            lines += ["You can now apply the upgrade by executing the following:", "",
                      f"    kubeadm upgrade apply v{target}", "",
                      "Then, on EACH node: kubectl drain <node> --ignore-daemonsets, "
                      "kubeadm upgrade node, kubectl uncordon <node>."]
        else:
            lines.append("Your cluster is already at the newest version this lab knows.")
        return True, "\n".join(lines)

    if sub == "apply":
        wanted = next((a for a in args[1:] if a.startswith("v") or a[0].isdigit()), "")
        if not wanted:
            return False, "usage: kubeadm upgrade apply v<version>"
        wanted = wanted.lstrip("v")
        if wanted not in RELEASES:
            return False, (f"version v{wanted} is not available. Known releases: "
                           + ", ".join("v" + r for r in RELEASES))
        current_minor, target_minor = minor(control_plane), minor(wanted)
        if target_minor < current_minor:
            return False, (f"downgrades are not supported: cluster is v{control_plane}")
        if target_minor[1] - current_minor[1] > 1 or target_minor[0] != current_minor[0]:
            return False, (f"you cannot skip minor versions: upgrade v{control_plane} "
                           f"-> v{next_release(control_plane)} first, one minor at a time")
        cluster.version = wanted
        control = next((n for n in cluster.list("Node")
                        if deep_get(n, "status.role") == "control-plane"), None)
        if control is not None:
            set_node_version(control, wanted)
        cluster.record("Normal", "ControlPlaneUpgraded",
                       f"Control plane upgraded to v{wanted}", "cluster", "default")
        return True, ("[upgrade/config] Reading configuration from the cluster...\n"
                      "[upgrade/versions] Cluster version: v" + control_plane + "\n"
                      f"[upgrade/apply] Upgrading to version v{wanted}\n"
                      "[upgrade/staticpods] Upgrading kube-apiserver, "
                      "kube-controller-manager, kube-scheduler, etcd\n\n"
                      f"[upgrade/successful] SUCCESS! Your cluster was upgraded to "
                      f"\"v{wanted}\".\n\n"
                      "Now upgrade the kubelet on each node:\n"
                      "  kubectl drain <node> --ignore-daemonsets\n"
                      "  kubeadm upgrade node --node <node>\n"
                      "  kubectl uncordon <node>")

    if sub == "node":
        name = flags.get("--node")
        if not isinstance(name, str):
            name = args[1] if len(args) > 1 else ""
        if not name:
            return False, ("usage: kubeadm upgrade node --node <name>\n"
                           "(on a real cluster you run this ON the node; here you name it)")
        node = cluster.get("Node", "", name)
        if node is None:
            return False, f'nodes "{name}" not found'
        if minor(node_version(node)) == minor(cluster.version):
            return True, f"[upgrade] node {name} is already at v{cluster.version}"
        if minor(node_version(node)) > minor(cluster.version):
            return False, (f"node {name} is newer than the control plane -- upgrade "
                           "the control plane first with `kubeadm upgrade apply`")
        if not deep_get(node, "spec.unschedulable", False):
            return False, (f"node {name} is still schedulable. Drain it first:\n"
                           f"  kubectl drain {name} --ignore-daemonsets")
        set_node_version(node, cluster.version)
        cluster.record("Normal", "NodeUpgraded",
                       f"kubelet on {name} upgraded to v{cluster.version}",
                       f"node/{name}", "default")
        return True, (f"[upgrade] Upgrading kubelet configuration on {name}\n"
                      f"[upgrade] The kubelet on {name} is now v{cluster.version}\n"
                      f"Remember: kubectl uncordon {name}")

    return False, f"unknown kubeadm upgrade command: {sub}"


def _kubeadm_certs(cluster: Cluster, args: List[str],
                   flags: Dict[str, Any]) -> Tuple[bool, str]:
    sub = args[0] if args else "check-expiration"
    if sub == "check-expiration":
        rows = ["CERTIFICATE                EXPIRES(days)   RESIDUAL   EXTERNALLY MANAGED"]
        for name, days in sorted(cluster.pki.items()):
            state = "no"
            rows.append(f"{name:<26} {days:<15} "
                        f"{'OK' if days > 30 else 'EXPIRING SOON':<10} {state}")
        rows.append("")
        rows.append("Certificates are renewed automatically by `kubeadm upgrade apply`, "
                    "or manually with `kubeadm certs renew all`.")
        return True, "\n".join(rows)
    if sub == "renew":
        what = args[1] if len(args) > 1 else "all"
        renewed = list(cluster.pki) if what == "all" else [what]
        for name in renewed:
            if name in cluster.pki:
                cluster.pki[name] = 364 if name != "ca" else 3650
        return True, ("certificate renewed: " + ", ".join(renewed) +
                      "\n\nRestart kube-apiserver, kube-controller-manager and "
                      "kube-scheduler for the new certificates to take effect.")
    return False, f"unknown kubeadm certs command: {sub}"


def age_certificates(cluster: Cluster, days: int = 1) -> None:
    for name in list(cluster.pki):
        cluster.pki[name] = max(0, cluster.pki[name] - days)
    for user in cluster.kubeconfig.get("users", {}).values():
        if "expires_in_days" in user:
            user["expires_in_days"] = max(0, user["expires_in_days"] - days)


