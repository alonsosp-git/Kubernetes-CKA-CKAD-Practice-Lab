REQUIRED_ETCD_FLAGS = ("--endpoints", "--cacert", "--cert", "--key")


def etcdctl(cluster: Cluster, args: List[str], flags: Dict[str, Any],
            env: Dict[str, str], base_dir: str) -> Tuple[bool, str]:
    if env.get("ETCDCTL_API") not in (None, "3"):
        return False, "this lab only speaks the v3 API: set ETCDCTL_API=3"
    if not args:
        return True, ETCDCTL_HELP
    action = args[0]

    if action == "member":
        return True, ("ID          STATUS    NAME                 PEER ADDRS"
                      "               CLIENT ADDRS\n"
                      "8e9e05c52164694d, started, lab-control-plane, "
                      "https://172.18.0.2:2380, https://172.18.0.2:2379")

    if action == "endpoint":
        return True, ("https://127.0.0.1:2379, 8e9e05c52164694d, 3.5.12, "
                      f"{max(1, len(cluster.all_objects()) // 4)} MB, true, false, "
                      f"{cluster.tick}, {cluster.tick}, {cluster.tick}")

    if action != "snapshot":
        return False, f"unknown etcdctl command: {action}"

    sub = args[1] if len(args) > 1 else ""
    path = args[2] if len(args) > 2 else flags.get("--data-dir", "")

    if sub in ("save", "restore"):
        missing = [f for f in REQUIRED_ETCD_FLAGS if f not in flags]
        if sub == "restore":
            missing = [f for f in missing if f != "--endpoints"]
        if missing:
            return False, ("Error: rpc error: code = Unavailable desc = "
                           "transport is closing\n\n"
                           "(you are missing " + ", ".join(missing) + ". Every "
                           "etcdctl call against a kubeadm cluster needs\n"
                           "  --endpoints=https://127.0.0.1:2379 \\\n"
                           "  --cacert=/etc/kubernetes/pki/etcd/ca.crt \\\n"
                           "  --cert=/etc/kubernetes/pki/etcd/server.crt \\\n"
                           "  --key=/etc/kubernetes/pki/etcd/server.key)")

    if sub == "save":
        if not path:
            return False, "usage: etcdctl snapshot save <file> [flags]"
        snapshot = cluster.snapshot()
        snapshot["version"] = cluster.version
        snapshot["taken_at_tick"] = cluster.tick
        payload = json.dumps(snapshot, default=str)
        cluster.etcd_snapshots[path] = {
            "data": snapshot,
            "revision": cluster.tick,
            "keys": len(cluster.all_objects()),
            "size": len(payload),
            "hash": hashlib.sha256(payload.encode()).hexdigest()[:8],
        }
        _write_side_file(base_dir, path, payload)
        return True, (f"{{\"level\":\"info\",\"msg\":\"fetching snapshot\"}}\n"
                      f"{{\"level\":\"info\",\"msg\":\"fetched snapshot\","
                      f"\"path\":\"{path}\"}}\n"
                      f"Snapshot saved at {path}")

    if sub == "status":
        if path not in cluster.etcd_snapshots:
            return False, f"stat {path}: no such file or directory"
        meta = cluster.etcd_snapshots[path]
        return True, ("HASH       REVISION   TOTAL KEYS   TOTAL SIZE\n"
                      f"{meta['hash']}   {meta['revision']:<10} {meta['keys']:<12} "
                      f"{meta['size'] // 1024 + 1} kB")

    if sub == "restore":
        if path not in cluster.etcd_snapshots:
            return False, (f"stat {path}: no such file or directory\n"
                           "(take one first: etcdctl snapshot save <file> …)")
        snapshot = cluster.etcd_snapshots[path]["data"]
        cluster.objects.clear()
        for obj in snapshot["objects"]:
            cluster.put(obj)
        cluster.tick = int(snapshot.get("tick", cluster.tick))
        cluster.load = dict(snapshot.get("load", {}))
        cluster.chaos = dict(snapshot.get("chaos", {}))
        cluster.record("Warning", "EtcdRestored",
                       f"etcd restored from {path} (revision "
                       f"{snapshot.get('taken_at_tick')})", "cluster", "default")
        return True, (f"{{\"level\":\"info\",\"msg\":\"restoring snapshot\","
                      f"\"path\":\"{path}\"}}\n"
                      f"{{\"level\":\"info\",\"msg\":\"restored snapshot\"}}\n\n"
                      f"Restored {len(snapshot['objects'])} objects "
                      f"(revision {snapshot.get('taken_at_tick')}).\n"
                      "On a real cluster you would now point the etcd static pod at "
                      "the new --data-dir and let the API server restart.")

    return False, f"unknown etcdctl snapshot command: {sub}"


def _write_side_file(base_dir: str, path: str, payload: str) -> None:
    """Also drop the snapshot on disk when the path is writable."""
    try:
        target = path if os.path.isabs(path) else os.path.join(base_dir, path)
        if os.path.isabs(path) and not os.path.isdir(os.path.dirname(target)):
            return
        os.makedirs(os.path.dirname(target) or ".", exist_ok=True)
        with open(target, "w", encoding="utf-8") as handle:
            handle.write(payload)
    except OSError:
        pass


