"""Cluster administration: kubeadm, etcdctl, PKI/kubeconfig and a container registry.

These are the CKA topics that a workload simulator normally cannot reach. They
are modelled here faithfully enough that the *procedure and its rules* are what
you practise -- which is exactly what the exam and a real upgrade night test:

  kubeadm   version skew rules, control plane first, drain -> upgrade -> uncordon
  etcdctl   the mandatory --endpoints/--cacert/--cert/--key flags, snapshot
            save / status / restore, and restoring into a live cluster
  PKI       CertificateSigningRequest -> approve -> issue -> kubeconfig entry,
            certificate expiry and renewal
  registry  build/tag/push, public vs private images, imagePullSecrets

What is NOT simulated: real machines, real TLS material, real container builds.
Those need kind/minikube and a real Docker daemon -- see README section 6.
"""
